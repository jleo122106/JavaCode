package com.mycompany.datatypesandvariablesb;

/**
 *
 * @author John Leo D. Martinez
 */
public class DatatypesandVariablesB {
    public static void main(String[] args) {

        // Reference-type variable for the full name
        String fullName = "John Leo D. Martinez";

        // Primitive-type variables
        int age = 18;
        double height = 1.67;       // Height in meters
        char initial = 'D';
        boolean isStudent = true;

        // Print each value on a separate, clearly labeled line
        System.out.println("Full Name: " + fullName);
        System.out.println("Age      : " + age);
        System.out.println("Height   : " + height + " meters");
        System.out.println("Initial  : " + initial);
        System.out.println("Student  : " + isStudent);
    }
}
